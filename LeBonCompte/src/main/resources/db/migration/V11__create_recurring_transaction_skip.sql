-- Remembers a month a user explicitly deleted a recurring transaction's generated instance for,
-- so it is never silently regenerated for that same month again.
CREATE TABLE recurring_transaction_skip (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurring_transaction_id BIGINT NOT NULL REFERENCES recurring_transaction (id) ON DELETE CASCADE,
    month                    DATE   NOT NULL,
    UNIQUE (recurring_transaction_id, month)
);
